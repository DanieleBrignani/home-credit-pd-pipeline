"""Generate docs/feature_lineage.md from the feature registry + source contracts (single source of truth)."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from creditrisk import config  # noqa: E402
from creditrisk.contracts import CONTRACTS  # noqa: E402
from creditrisk.features import FEATURE_REGISTRY, feature_counts, feature_schema_version  # noqa: E402

AGGREGATION = {
    "application_train": "none (already at applicant grain)",
    "bureau": "GROUP BY SK_ID_CURR after joining bureau_balance rolled up per SK_ID_BUREAU",
    "bureau_balance": "GROUP BY SK_ID_BUREAU (months, delinquent months, worst status), then rolled to SK_ID_CURR",
    "previous_application": "GROUP BY SK_ID_CURR (counts, rates, means)",
    "installments_payments": "GROUP BY SK_ID_CURR (late share, days late, payment ratios, last-12-month window)",
    "credit_card_balance": "GROUP BY SK_ID_CURR over card-months (utilisation, DPD)",
    "POS_CASH_balance": "GROUP BY SK_ID_CURR over loan-months (DPD only; deliberately small)",
    "application_test": "NOT USED (no TARGET; ingested only for lineage completeness)",
}

EXCLUDED = [
    ("TARGET", "application_train", "target leakage", "The label. Only ever read as `y` in stg_application; never in any feature SQL (test_leakage)."),
    ("SK_ID_CURR / SK_ID_PREV / SK_ID_BUREAU", "all", "identifier", "Keys, not signal; excluded from the matrix (a row id can encode ingestion order)."),
    ("CODE_GENDER", "application_train", "policy", "Protected attribute; not selected in staging. `days_birth` (age) IS used - see Residual risks."),
    ("DAYS_FIRST_DRAWING, DAYS_FIRST_DUE, DAYS_LAST_DUE_1ST_VERSION, DAYS_LAST_DUE, DAYS_TERMINATION", "previous_application",
     "post-outcome / temporal", "Realised repayment-timeline dates of earlier loans; can be positive (after the current application) and use the 365243 placeholder. Never staged."),
    ("DAYS_ENDDATE_FACT", "bureau", "post-outcome", "Actual end of a bureau credit; may postdate the application. Never staged."),
    ("Installments with DAYS_INSTALMENT > 0 or DAYS_ENTRY_PAYMENT > 0", "installments_payments", "temporal",
     "Rows describing the future relative to the application are filtered in int_installments_agg."),
    ("Card / POS rows with MONTHS_BALANCE >= 0", "credit_card_balance, POS_CASH_balance", "temporal",
     "Months at/after the application month are filtered (strictly `< 0`)."),
    ("Bureau rows with DAYS_CREDIT > 0; bureau_balance MONTHS_BALANCE > 0", "bureau, bureau_balance", "temporal", "Filtered."),
    ("Previous applications with DAYS_DECISION >= 0", "previous_application", "temporal", "Decision not yet taken before this application; filtered."),
    ("Building/housing block (47 `*_AVG/_MODE/_MEDI` columns), FLAG_DOCUMENT_*, contact flags", "application_train",
     "opacity / sparsity", "Not leakage; excluded to avoid hundreds of opaque, 50-70% missing columns (scope choice, documented in README Trade-offs)."),
]

FAMILIES = [
    ("A. application raw", "Core underwriting inputs known on the application form: income, credit, annuity, goods price, "
     "employment/age, external scores. Kept raw because these are the most predictive and auditable inputs."),
    ("B. affordability ratios", "Credit/income, annuity/income, implied term: the debt-service view an underwriter uses. "
     "Ratios are computed in one Python function shared by training and serving to prevent skew."),
    ("C. bureau history", "How much external debt, how overdue, how long a history: classic bureau-style attributes. "
     "Rolled up from credit-level and monthly-status grain."),
    ("D. previous applications", "Behaviour at this lender: refusal rate and volume are strong prior-risk signals. Only decision-time fields."),
    ("E. installment behaviour", "Realised payment discipline on earlier loans (lateness, underpayment, recent window). "
     "Restricted to payments dated on/before the application."),
    ("F. credit-card behaviour", "Utilisation and delinquency: revolving-credit stress."),
    ("G. POS/cash behaviour", "Only DPD summaries; other fields add little beyond installments and bloat the feature count."),
    ("H. history presence", "Explicit has-history flags so 'no history' (thin file) is distinguishable from 'zero events'."),
]


def main() -> None:
    L: list[str] = []
    a = L.append
    a("# Feature lineage and leakage audit\n")
    a(f"> Generated by `scripts/gen_feature_lineage.py` from `src/creditrisk/features.py` and `contracts.py`. "
      f"Do not edit by hand. Feature pipeline `{config.FEATURE_PIPELINE_VERSION}`, schema `{feature_schema_version()}`.\n")
    a("**Prediction time** = the moment an application is submitted. Every Home Credit `DAYS_*` / `MONTHS_BALANCE` field is "
      "relative to that moment (negative = before). A value is *available at prediction time* only if its timestamp is on/before it.\n")
    c = feature_counts()
    a("## 1. Counts\n")
    a("| item | n |\n|---|---|")
    for k, v in c.items():
        a(f"| {k} | {v} |")
    a("\n## 2. Source grain, keys, cardinality, aggregation\n")
    a("| table | grain | primary key | join to parent | aggregation to applicant grain |\n|---|---|---|---|---|")
    for t in CONTRACTS.values():
        a(f"| `{t.name}` | {t.grain} | `{', '.join(t.pk)}` | {t.parent or '-'} | {AGGREGATION[t.name]} |")
    a("\nJoin path: `bureau_balance -N:1-> bureau -N:1-> application`; `installments / credit_card / POS_CASH -N:1-> "
      "previous_application -N:1-> application`. Each history source is aggregated to one row per `SK_ID_CURR` *before* joining, "
      "so the final left joins are 1:1 and cannot fan out the training grain (asserted by the unique test on the applicant key "
      "and by `test_integration`).\n")
    a("## 3. Per-feature record\n")
    a("| feature | family | source | transformation | availability at prediction time |\n|---|---|---|---|---|")
    for f in FEATURE_REGISTRY:
        a(f"| `{f.name}` | {f.family} | {f.source} | {f.transformation} | {f.availability} |")
    a("\n## 4. Feature families and rationale\n")
    for fam, why in FAMILIES:
        n = sum(1 for f in FEATURE_REGISTRY if f.family == fam)
        a(f"- **{fam}** ({n}): {why}")
    a("\n## 5. Leakage audit\n")
    a("Three classes were audited explicitly.\n")
    a("1. **Target leakage** - any column that is, or is derived from, `TARGET`. Control: `TARGET` is read only in `stg_application` "
      "and only used as `y`; `build_features` takes a frame and returns exactly `FEATURE_COLUMNS`; `assert_no_forbidden` runs in "
      "`data.split_frames`; static SQL scan in `tests/test_leakage.py`.")
    a("2. **Temporal leakage** - history rows dated after the application. Control: every intermediate dbt model carries a guard "
      "(`days_credit <= 0`, `days_decision < 0`, `days_instalment <= 0`, `months_balance < 0`), tested statically and by an independent "
      "pandas re-implementation in `tests/test_integration.py` using fixtures that contain deliberate future-dated trap rows.")
    a("3. **Post-outcome information** - fields written after the loan outcome is known (realised end dates, termination). Control: "
      "never staged (table below).\n")
    a("### Excluded / guarded fields\n")
    a("| field | source | class | handling |\n|---|---|---|---|")
    for r in EXCLUDED:
        a("| " + " | ".join(r) + " |")
    a("\n## 6. Residual risks (not eliminated)\n")
    a("- **No absolute dates.** Home Credit provides only relative days, so true point-in-time reconstruction cannot be verified; the "
      "guards rely on the dataset's own relative-day semantics. Train/valid/test is a *deterministic hash split*, not a time split, so "
      "reported performance is an in-time estimate and will be optimistic relative to a genuine out-of-time deployment.")
    a("- **Snapshot semantics of bureau amounts.** `AMT_CREDIT_SUM_DEBT` etc. are documented as of the application; we cannot verify "
      "from the data that none were refreshed later.")
    a("- **Orphan bureau-balance rows.** On the real data a large block of `bureau_balance` rows references an `SK_ID_BUREAU` that is absent "
      "from `bureau`. They cannot be attributed to an applicant, so the inner path through `bureau` drops them; the dbt relationship test reports "
      "them as a warning. Bureau delinquency features therefore describe only the credits that are present in `bureau`.")
    a("- **`EXT_SOURCE_*`** are third-party scores of undisclosed construction; they are available at application time but their own "
      "lineage is opaque and they dominate the model. Dependence on them is a governance risk.")
    a("- **Age (`days_birth`)** is retained as an underwriting input; use of age may be restricted by regulation in some jurisdictions. "
      "`CODE_GENDER` is excluded. No fairness audit has been performed.")
    a("- **Presence flags** (`has_*_history`) reflect data-provider coverage and could proxy for population segments.")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "feature_lineage.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/feature_lineage.md")


if __name__ == "__main__":
    main()
