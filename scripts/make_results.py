"""Render measured results from reports/*.json into README.md / RECRUITER_SUMMARY.md marker blocks and reports/RESULTS.md.

Refuses to run unless reports/metrics.json has status CANONICAL (real Kaggle files). Every number in the blocks comes
straight from a JSON file produced by a repository command; nothing is typed by hand.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REP = ROOT / "reports"  # tests monkeypatch this
START, END = "<!-- RESULTS:START (generated by scripts/make_results.py; do not edit) -->", "<!-- RESULTS:END -->"
R_START, R_END = "<!-- MEASURED:START (generated by scripts/make_results.py; do not edit) -->", "<!-- MEASURED:END -->"


def load(name, required=True):
    p = REP / name
    if not p.exists():
        if required:
            raise SystemExit(f"missing {p}: run the producing command first (see docs/reproducibility.md)")
        return None
    return json.loads(p.read_text())


def f(x, d=4):
    return f"{x:.{d}f}"


def render_block() -> tuple[str, str]:
    m = load("metrics.json")
    if m["status"] != "CANONICAL":
        raise SystemExit("metrics.json is NON_CANONICAL (not the real Kaggle files): refusing to publish results")
    rt = load("runtime.json", False) or {}
    bench = load("inference_benchmark.json", False)
    drift = load("drift_simulation.json", False)
    life = load("lifecycle_demo.json", False)
    sel = m["selected_on_validation"]
    mod = m["models"]
    names = {"logreg": "Logistic regression (baseline)", "lightgbm": "LightGBM (+ calibration if it helped on validation)"}
    L = []
    a = L.append
    a(f"Source: `reports/metrics.json` (git `{m['git_commit'][:10]}`, dataset `{m['data_provenance']['dataset_version']}`, "
      f"feature schema `{m['feature_schema_version']}`, feature-table fingerprint `{m['feature_table_fingerprint']}`).\n")
    a("**Data used (canonical Kaggle files, row counts verified at ingest)**\n")
    a("| table | rows |\n|---|---|")
    for t, v in sorted(m["data_provenance"]["files"].items()):
        a(f"| {t} | {v['rows']:,} |")
    s = m["split_sizes"]
    a(f"\nHash split of labeled applications: train {s['train']:,} / validation {s['valid']:,} / test {s['test']:,}. "
      f"Default rate (test): {mod[sel]['test']['prevalence']*100:.2f}%.\n")
    a(f"**Selected on validation evidence: `{sel}`**\n")
    a("| model | split | ROC-AUC | PR-AUC | Brier | Brier (predict-prevalence) | KS | calib. slope | calib. intercept |\n|---|---|---|---|---|---|---|---|---|")
    for n in ("logreg", "lightgbm"):
        for sp in ("valid", "test"):
            x = mod[n][sp]
            a(f"| {names[n]} | {sp} | {f(x['roc_auc'])} | {f(x['pr_auc'])} | {f(x['brier'],5)} | {f(x['brier_baseline_prevalence'],5)} | "
              f"{f(x['ks'])} | {f(x['calibration_slope'],3)} | {f(x['calibration_intercept'],3)} |")
    a("\n**Precision / recall at thresholds frozen on validation, applied to the untouched test set**\n")
    a("| model | rule | threshold | flag rate | precision | recall |\n|---|---|---|---|---|---|")
    for n in ("logreg", "lightgbm"):
        for r in mod[n]["test_threshold_table"]:
            a(f"| {n} | {r['rule']} | {f(r['threshold'],4)} | {r['flag_rate']*100:.1f}% | {r['precision']*100:.1f}% | {r['recall']*100:.1f}% |")
    a("\n**Runtime and size**\n")
    a("| item | value | source |\n|---|---|---|")
    c = m["feature_counts"]
    a(f"| engineered features (aggregates + derived) | {c['engineered_total (aggregates + derived)']} | `features.feature_counts()` |")
    a(f"| model input columns | {c['total_model_input_columns']} | same |")
    a(f"| training wall-clock, all candidates incl. search | {m['training_seconds_total']:.0f} s | `reports/metrics.json` |")
    a(f"| logistic regression fit (3-value grid) | {mod['logreg']['fit_seconds']:.0f} s | same |")
    a(f"| LightGBM random search ({m['run_config']['n_iter']} configs) | {mod['lightgbm']['fit_seconds']:.0f} s | same |")
    if "feature_pipeline_dbt_build" in rt:
        a(f"| feature pipeline (dbt build: staging, intermediate, marts, tests) | {rt['feature_pipeline_dbt_build']['seconds']:.0f} s | `reports/runtime.json` |")
    if "ingest" in rt:
        a(f"| raw ingest (COPY into Postgres) | {rt['ingest']['seconds']:.0f} s | `reports/runtime.json` |")
    if bench:
        b = bench["client_latency_ms"]
        a(f"| `/predict` latency p50 / p95 / p99 | {b['p50']:.1f} / {b['p95']:.1f} / {b['p99']:.1f} ms | `reports/inference_benchmark.json` |")
        a(f"| benchmark conditions | {bench['n_requests']:,} sequential requests, {bench['errors']} errors, model v{bench['model_version']} "
          f"({bench['model_family']}), {bench['conditions']['cpu_count']} logical CPUs | same |")
    a("\nTimings depend on the machine; they are measured, not bit-reproducible. Metrics are reproducible (see `scripts/reproduce_check.py`).")
    if drift:
        a("\n**Drift monitor sanity check (static data; see Monitoring)**\n")
        a("| comparison | score PSI | worst monitored-feature PSI |\n|---|---|---|")
        for k in ("baseline_train_vs_valid", "baseline_train_vs_test"):
            blk = drift[k]
            worst = max(v["psi"] for kk, v in blk.items() if isinstance(v, dict))
            a(f"| {k} | {f(blk['score']['psi'],5)} | {f(worst,5)} |")
        a("\n| INJECTED perturbation (synthetic, not observed) | score PSI | status |\n|---|---|---|")
        for k, v in drift["injected_shift_detection"].items():
            a(f"| {k} | {f(v['score_psi'],4)} | {v['score_status']} |")
    if life:
        a("\n**Champion / challenger / rollback drill** (`reports/lifecycle_demo.json`, decisions in `reports/model_decisions.jsonl`)\n")
        for d in life["decision_history"]:
            if d["kind"] in ("promoted", "rejected"):
                a(f"- {d['ts'][:19]}Z version {d['version']}: **{d['kind'].upper()}**")
                for chk in d.get("checks", []):
                    a(f"  - {chk['gate']}: {'pass' if chk['passed'] else 'FAIL'} ({chk['detail']})")
        rb = life.get("rollback_drill")
        if isinstance(rb, dict):
            a(f"- rollback drill: champion v{rb['from']} -> v{rb['to']}, then rolled forward to v{life['roll_forward']['to']}")
        else:
            a(f"- rollback drill: {rb}")
    readme_block = "\n".join(L)

    k = [f"Measured on the real Home Credit data, selected model `{sel}`, held-out test split "
         f"({s['test']:,} applications, default rate {mod[sel]['test']['prevalence']*100:.2f}%):\n"]
    t, bl = mod[sel]["test"], mod["logreg"]["test"]
    k.append(f"- ROC-AUC {f(t['roc_auc'],3)} (logistic baseline {f(bl['roc_auc'],3)}); PR-AUC {f(t['pr_auc'],3)} (baseline {f(bl['pr_auc'],3)}); "
             f"KS {f(t['ks'],3)}; Brier {f(t['brier'],4)} vs {f(t['brier_baseline_prevalence'],4)} for predicting the base rate.")
    if bench:
        k.append(f"- `/predict` p50 {bench['client_latency_ms']['p50']:.1f} ms, p95 {bench['client_latency_ms']['p95']:.1f} ms "
                 f"(single client, local machine, includes DB lookup and audit write).")
    if "feature_pipeline_dbt_build" in rt:
        k.append(f"- Feature pipeline (dbt, ~{sum(1 for _ in m['data_provenance']['files'])} source tables) rebuilt in {rt['feature_pipeline_dbt_build']['seconds']:.0f} s; "
                 f"{c['engineered_total (aggregates + derived)']} engineered features.")
    return readme_block, "\n".join(k)


def splice(path: Path, start: str, end: str, body: str) -> None:
    txt = path.read_text(encoding="utf-8")
    if start not in txt or end not in txt:
        raise SystemExit(f"{path.name}: marker block missing")
    new = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: f"{start}\n{body}\n{end}", txt, flags=re.S)
    path.write_text(new, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if README blocks differ from regenerated ones")
    a = ap.parse_args()
    readme_block, measured = render_block()
    (REP / "RESULTS.md").write_text("# Results (generated)\n\n" + readme_block + "\n", encoding="utf-8")
    if a.check:
        ok = True
        for path, s, e, body in ((ROOT / "README.md", START, END, readme_block), (ROOT / "RECRUITER_SUMMARY.md", R_START, R_END, measured)):
            cur = re.search(re.escape(s) + r"\n(.*?)\n" + re.escape(e), path.read_text(encoding="utf-8"), flags=re.S)
            if not cur or cur.group(1) != body:
                print(f"STALE: {path.name} results block differs from reports/*.json"); ok = False
        return 0 if ok else 1
    splice(ROOT / "README.md", START, END, readme_block)
    splice(ROOT / "RECRUITER_SUMMARY.md", R_START, R_END, measured)
    print("README.md and RECRUITER_SUMMARY.md updated from reports/*.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
